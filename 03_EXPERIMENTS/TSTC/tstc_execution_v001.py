"""TGCV WP2 TSTC bounded execution runner v001.

Runs only the frozen synthetic fixtures and records structural accessibility
changes. It contains no real-data access, outcome access, sampling, network
access, or value analysis.

Important: this runner deliberately fails closed when a frozen cross-domain
coupling cannot be generated by the declared fixture transition operators.
It does not repair or mutate the frozen fixtures.
"""
from __future__ import annotations

import json
import platform
import sys
from copy import deepcopy
from pathlib import Path

from tstc_fixture_engine_v001 import fixtures, tacc, apply_checked, digest


def _transition_by_id(fixture, transformation_id, state, context):
    for t in fixture.transformations:
        if t.transformation_id == transformation_id:
            if not t.predicate(state, context):
                raise AssertionError(f"inaccessible trajectory transformation: {transformation_id}")
            return apply_checked(state, context, t.transition, t.affected_variables)
    raise AssertionError(f"unknown transformation: {transformation_id}")


def _run_single_fixture(fixture):
    s0, c0 = deepcopy(fixture.state), deepcopy(fixture.context)
    t0, _ = tacc(fixture, s0, c0)

    s1, c1, intervention_changed = apply_checked(
        s0, c0, fixture.intervention, fixture.declared_intervention_variables
    )
    t1, _ = tacc(fixture, s1, c1)

    ns, nc, negative_changed = apply_checked(
        s0, c0, fixture.negative_control, fixture.declared_negative_control_variables
    )
    nt, _ = tacc(fixture, ns, nc)
    if set(nt) != set(t0):
        raise AssertionError(
            f"negative control violation for {fixture.fixture_id}: {set(t0)^set(nt)}"
        )

    return {
        "fixture_id": fixture.fixture_id,
        "fixture_version": fixture.fixture_version,
        "connector_id": fixture.transformations[0].domain,
        "intervention_id": fixture.intervention_id,
        "S0": s0,
        "C0": c0,
        "T_acc_0": t0,
        "intervention": {
            "S1": s1,
            "C1": c1,
            "changed_variables": intervention_changed,
        },
        "T_acc_1": t1,
        "Delta_T_acc": {
            "opened": tuple(sorted(set(t1) - set(t0))),
            "closed": tuple(sorted(set(t0) - set(t1))),
            "persistent": tuple(sorted(set(t0) & set(t1))),
            "changed": t0 != t1,
        },
        "negative_control": {
            "changed_variables": negative_changed,
            "T_acc": nt,
            "delta": tuple(sorted(set(nt) ^ set(t0))),
        },
        "trajectory": [],
        "limitations": [],
        "non_claims": [
            "No scientific validity claim",
            "No causal claim",
            "No superiority claim",
            "No value claim",
        ],
    }


def run_execution():
    results = [_run_single_fixture(f) for f in fixtures()]
    return {
        "engine_version": "TSTC_FIXTURE_ENGINE_v001",
        "execution_version": "TSTC_EXECUTION_v001",
        "mode": "TSTC_SYNTHETIC_EXECUTION",
        "execution_metadata": {
            "python": sys.version,
            "platform": platform.platform(),
            "source": str(Path(__file__).resolve()),
            "random_seed": None,
        },
        "results": results,
    }


if __name__ == "__main__":
    print(json.dumps(run_execution(), sort_keys=True, indent=2, default=list))
