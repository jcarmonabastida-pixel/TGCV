"use strict";
const assert = require("node:assert/strict");
const { scoreGraph, evaluateCases } = require("./ocr_graph_evaluator_v02.cjs");
const fixtures = require("./ocr_graph_evaluation_fixtures_v02.json");
const results = evaluateCases(fixtures.cases);
assert.equal(results.length, 10);
assert.ok(results.every(r => r.expectation_met), results.filter(r => !r.expectation_met).map(r => r.id + ": expected " + r.expected_status + " got " + r.status).join("\n"));
const textOnly = results.find(r => r.id === "STRUCT-002-labels-wrong-topology-right");
assert.equal(textOnly.status, "STRUCTURE_PASS");
assert.equal(textOnly.structural_metrics.exact_topology_match, true);
assert.equal(textOnly.text_metrics.node_label_errors, 2);
assert.equal(textOnly.text_metrics.provisional_labels_on_matched_nodes, 2);
const reversed = results.find(r => r.id === "STRUCT-003-reversed-arrow");
assert.ok(reversed.critical_failures.includes("directed_edge_reversal"));
const missingEdge = results.find(r => r.id === "STRUCT-004-missing-edge");
assert.equal(missingEdge.structural_metrics.missing_edges, 1);
const extra = results.find(r => r.id === "STRUCT-005-extra-edge");
assert.equal(extra.structural_metrics.extra_edges, 1);
assert.ok(results.find(r => r.id === "STRUCT-006-duplicate-edge").critical_failures.includes("duplicate_edges"));
assert.ok(results.find(r => r.id === "STRUCT-007-missing-node").critical_failures.includes("node_set_mismatch"));
assert.ok(results.find(r => r.id === "STRUCT-008-unknown-endpoint").critical_failures.includes("edge_endpoint_missing"));
assert.equal(results.find(r => r.id === "STRUCT-009-undirected-equivalence").status, "STRUCTURE_PASS");
assert.equal(results.find(r => r.id === "STRUCT-010-edge-label-wrong-topology-right").status, "STRUCTURE_PASS");
assert.throws(() => scoreGraph({nodes:[{id:"n1",label:"A"},{id:"n1",label:"dup"}],edges:[]},{nodes:[],edges:[]}), /duplicate node id/);
process.stdout.write("PASS: " + results.length + "/" + results.length + " structure-first fixture expectations; topology/text separation and critical-error checks passed.\n");
