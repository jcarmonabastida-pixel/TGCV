"use strict";
const assert = require("node:assert/strict");
const { scoreGraph, evaluateCases } = require("./ocr_graph_evaluator.cjs");
const fixtures = require("./ocr_graph_evaluation_fixtures.json");

const results = evaluateCases(fixtures.cases);
assert.equal(results.length, 9);
assert.ok(results.every(r => r.expectation_met), results.filter(r => !r.expectation_met).map(r => r.id + ": expected " + r.expected_status + " got " + r.status).join("\n"));
const exact = results.find(r => r.id === "GRAPH-001-exact-match");
assert.equal(exact.topology_metrics.f1, 1);
assert.equal(exact.edge_label_metrics.f1, 1);
assert.equal(exact.topology_match, true);
const reverse = results.find(r => r.id === "GRAPH-002-reversed-arrow");
assert.equal(reverse.reversed_directed_edges, 1);
assert.ok(reverse.critical_failures.includes("directed_edge_reversal"));
const spurious = results.find(r => r.id === "GRAPH-003-spurious-edge");
assert.ok(spurious.critical_failures.includes("spurious_or_duplicate_edges"));
const missing = results.find(r => r.id === "GRAPH-004-missing-edge");
assert.ok(missing.critical_failures.includes("missing_edges"));
const wrongLabel = results.find(r => r.id === "GRAPH-005-wrong-node-label");
assert.equal(wrongLabel.status, "PASS");
assert.equal(wrongLabel.semantic_review_required, true);
const duplicate = results.find(r => r.id === "GRAPH-006-duplicate-edge");
assert.ok(duplicate.critical_failures.length > 0);
const undirected = results.find(r => r.id === "GRAPH-007-undirected-match");
assert.equal(undirected.status, "PASS");
const provisional = results.find(r => r.id === "GRAPH-009-provisional-node-ids-and-unreadable-transition-label");
assert.equal(provisional.topology_match, true);
assert.equal(provisional.semantic_review_required, true);
assert.equal(provisional.exact_edge_labels, false);
assert.throws(() => scoreGraph({nodes:[{id:"A",label:"A"},{id:"A",label:"dup"}],edges:[]},{nodes:[],edges:[]}), /duplicate node id/);
assert.throws(() => scoreGraph({nodes:[{id:"A",label:"A"}],edges:[{source:"A",target:"MISSING",direction:"directed",label:""}]},{nodes:[],edges:[]}), /missing node/);
process.stdout.write("PASS: " + results.length + "/" + results.length + " topology-first fixture expectations; semantic-review, critical-topology and input-validation checks passed.\n");
